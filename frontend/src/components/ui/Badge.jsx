import { ACTION_META, CATEGORY_LABELS, CLASSIFICATION_META, SEVERITY_META, SOURCE_META } from '../../lib/constants.js';

export function Badge({ className = '', icon: Icon, children, title }) {
  return (
    <span
      title={title}
      className={`inline-flex items-center gap-1 whitespace-nowrap rounded px-1.5 py-0.5 text-xs font-medium ring-1 ring-inset ${className}`}
    >
      {Icon && <Icon className="size-3 shrink-0" aria-hidden="true" />}
      {children}
    </span>
  );
}

export function SeverityBadge({ severity }) {
  const meta = SEVERITY_META[severity] ?? SEVERITY_META.info;
  return (
    <Badge className={meta.badge} icon={meta.icon}>
      {meta.label}
    </Badge>
  );
}

export function ActionBadge({ action }) {
  const meta = ACTION_META[action];
  if (!meta) return null;
  return (
    <Badge className={meta.badge} icon={meta.icon}>
      {meta.label}
    </Badge>
  );
}

export function ClassificationBadge({ classification }) {
  const meta = CLASSIFICATION_META[classification];
  if (!meta) return null;
  return <Badge className={meta.badge}>{meta.label}</Badge>;
}

export function SourceBadge({ sourceType }) {
  const meta = SOURCE_META[sourceType];
  if (!meta) return null;
  return (
    <Badge
      className={meta.badge}
      icon={meta.icon}
      title={sourceType === 'simulator' ? 'Generated by the controlled simulator; not real traffic' : undefined}
    >
      {meta.label}
    </Badge>
  );
}

export function categoryLabel(category) {
  return CATEGORY_LABELS[category] ?? category;
}

const STATUS_STYLES = {
  online: { dot: 'bg-emerald-400', text: 'text-emerald-300', label: 'Online' },
  offline: { dot: 'bg-red-400', text: 'text-red-300', label: 'Offline' },
  'never-connected': { dot: 'bg-slate-500', text: 'text-ink-3', label: 'No heartbeat yet' },
  ok: { dot: 'bg-emerald-400', text: 'text-emerald-300', label: 'Operational' },
  degraded: { dot: 'bg-amber-400', text: 'text-amber-300', label: 'Degraded' },
  down: { dot: 'bg-red-400', text: 'text-red-300', label: 'Unavailable' },
  unknown: { dot: 'bg-slate-500', text: 'text-ink-3', label: 'Checking…' },
};

/** Status dot + label. The label always accompanies the colour. */
export function StatusIndicator({ status, label, className = '' }) {
  const style = STATUS_STYLES[status] ?? STATUS_STYLES.unknown;
  return (
    <span className={`inline-flex items-center gap-1.5 text-xs font-medium ${style.text} ${className}`}>
      <span className={`size-2 shrink-0 rounded-full ${style.dot}`} aria-hidden="true" />
      {label ?? style.label}
    </span>
  );
}
